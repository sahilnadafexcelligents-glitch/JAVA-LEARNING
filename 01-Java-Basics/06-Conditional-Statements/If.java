public class If {
    public static void main(String[] args) {

        /*
         * int a = 20;
         * if (a == 20) {
         * System.out.println("Same Value");
         * } else {
         * System.out.println("Not Same");
         * }
         */

        int a = 20;
        if (a == 20) {
            System.out.println("Same Value");
        } else if (a == 30) {
            System.out.println("Value is 30");
        } else {
            System.out.println("Not Same or 30");
        }
    }
}